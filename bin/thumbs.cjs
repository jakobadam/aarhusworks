// Small copies of the images the front page shows beside each post, plus the
// author portrait, so the feed doesn't download full-size figures (~4 MB) to
// draw 160x107 boxes. GitHub Pages can't resize images, so the copies are
// generated here and committed.
//
// Run after a Jekyll build whenever a post adds or changes its first image:
//   node bin/thumbs.cjs
// It reads the thumbnail srcs from _site/index.html, writes cover-cropped
// 320x214 WebP files (2x the desktop box) to assets/thumbs/, and records
// original src -> thumb in _data/thumbs.yml, which _layouts/home.html looks
// up (falling back to the original). Source images are never modified.
const path = require('path'), fs = require('fs');
const repo = path.resolve(__dirname, '..');
const puppeteer = require(path.join(repo, 'node_modules', 'puppeteer'));

const W = 320, H = 214, Q = 0.72;
const MIME = { '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp', '.gif': 'image/gif' };
const dataFile = path.join(repo, '_data', 'thumbs.yml');

// Existing map, so thumbs for srcs already swapped in the built page are kept.
const map = {};
if (fs.existsSync(dataFile))
  for (const m of fs.readFileSync(dataFile, 'utf8').matchAll(/^"(.+)": "(.+)"$/gm)) map[m[1]] = m[2];

const html = fs.readFileSync(path.join(repo, '_site', 'index.html'), 'utf8');
const srcs = [...html.matchAll(/class="post-card-thumb" src="([^"]+)"/g)].map(m => m[1])
  .filter(s => !s.startsWith('/assets/thumbs/'));

const localPath = src => {
  const p = decodeURIComponent(src.replace(/^https?:\/\/aarhusworks\.com/, '').split(/[?#]/)[0]);
  return p.startsWith('/') ? path.join(repo, p) : null;
};

(async () => {
  const b = await puppeteer.launch({ args: ['--no-sandbox'] });
  const page = await b.newPage();
  const shrink = async (file, w, h) => {
    const url = `data:${MIME[path.extname(file).toLowerCase()]};base64,` + fs.readFileSync(file).toString('base64');
    const out = await page.evaluate(async (url, w, h, q) => {
      const img = new Image(); img.src = url; await img.decode();
      const s = Math.max(w / img.naturalWidth, h / img.naturalHeight);   // object-fit: cover
      const c = document.createElement('canvas'); c.width = w; c.height = h;
      const g = c.getContext('2d'); g.imageSmoothingQuality = 'high';
      g.fillStyle = '#fff'; g.fillRect(0, 0, w, h);
      const dw = img.naturalWidth * s, dh = img.naturalHeight * s;
      g.drawImage(img, (w - dw) / 2, (h - dh) / 2, dw, dh);
      return c.toDataURL('image/webp', q);
    }, url, w, h, Q);
    return Buffer.from(out.split(',')[1], 'base64');
  };

  fs.mkdirSync(path.join(repo, 'assets', 'thumbs'), { recursive: true });
  for (const src of srcs) {
    const file = localPath(src);
    if (!file || !fs.existsSync(file) || !MIME[path.extname(file).toLowerCase()]) { console.log('skip', src); continue; }
    const rel = path.relative(path.join(repo, 'assets'), file).replace(/[\\/]/g, '-').replace(/\.[^.]+$/, '.webp');
    fs.writeFileSync(path.join(repo, 'assets', 'thumbs', rel), await shrink(file, W, H));
    map[src] = `/assets/thumbs/${rel}`;
    console.log(`${(fs.statSync(file).size / 1024) | 0} kB -> ${(fs.statSync(path.join(repo, 'assets', 'thumbs', rel)).size / 1024) | 0} kB  ${rel}`);
  }

  // Portrait: shown at 20, 44 and 64 px; 128 px covers 2x screens.
  const portrait = path.join(repo, 'assets', 'profil.png');
  if (fs.existsSync(portrait)) fs.writeFileSync(path.join(repo, 'assets', 'images', 'profil-128.webp'), await shrink(portrait, 128, 128));

  await b.close();
  fs.mkdirSync(path.dirname(dataFile), { recursive: true });
  fs.writeFileSync(dataFile, '# Generated by bin/thumbs.cjs -- original thumbnail src -> small copy.\n' +
    Object.keys(map).sort().map(k => `"${k}": "${map[k]}"`).join('\n') + '\n');
})();
